#!/usr/bin/env python3
"""Generate tests/vectors/dial_frame.txt from SPEC.md's frame description.

A third implementation, written from the format description and from neither the hub's nor the
device's code, so a shared misreading shows up as a disagreement. Do not hand-edit the output.

  encode  <name>  <type>  <payload-hex>  <frame-hex>
  stream  <name>  <input-hex>  <type:payload-hex,...|->  <discarded>  <corrupt>
"""
from pathlib import Path

MAGIC = b"\xa5\x45"      # 'E': Agent Dial. Upstream's Harness dial uses A5 48 ('H').
VER, MAX = 1, 8192

def crc16(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc

assert crc16(b"123456789") == 0x29B1

def frame(t: int, payload: bytes, ver: int = VER) -> bytes:
    assert len(payload) <= MAX
    body = bytes([ver, t]) + len(payload).to_bytes(2, "little") + payload
    return MAGIC + body + crc16(body).to_bytes(2, "little")

def decode(stream: bytes):
    """Reference decoder: the resync rules in SPEC.md, one byte at a time where it says so."""
    buf, out, discarded, corrupt = bytearray(stream), [], 0, 0
    while buf:
        if buf[0] != 0xA5 or (len(buf) > 1 and buf[1] != 0x45):
            buf.pop(0); discarded += 1; continue
        if len(buf) < 6: break
        n = int.from_bytes(buf[4:6], "little")
        if n > MAX:
            buf.pop(0); discarded += 1; continue
        if len(buf) < 8 + n: break
        body, crc = bytes(buf[2:6 + n]), int.from_bytes(buf[6 + n:8 + n], "little")
        if crc16(body) != crc:
            buf.pop(0); discarded += 1; corrupt += 1; continue
        out.append((buf[3], bytes(buf[6:6 + n])))
        del buf[:8 + n]
    return out, discarded, corrupt

J = lambda s: s.encode()
encodes = [
    ("json_empty_object", 1, J("{}")),
    ("json_hello", 1, J('{"t":"hello","product":"agent-dial","proto":1}')),
    ("json_utf8", 1, '{"t":"summary","text":"Cooking… ✓ đã xong"}'.encode()),
    ("json_payload_holds_magic", 1, J('{"t":"x","v":"') + b"\xa5\x45\xa5\x45" + J('"}')),
    ("pcm_zero_length", 2, b""),
    ("pcm_eight_bytes", 2, bytes.fromhex("00ff7f8001fea545")),
    ("log_line", 4, J("AD_HARDWARE board=m5stack-stopwatch w=468 h=466")),
    ("shot_chunk", 5, bytes(range(256)) * 4),
    ("unknown_type", 0x7F, J("?")),
    ("max_payload", 2, bytes((i * 7) & 0xFF for i in range(MAX))),
]
hello = frame(1, J('{"t":"hello"}'))
ping = frame(1, J('{"t":"ping"}'))
pcm = frame(2, bytes(16))
bad = bytearray(ping); bad[-1] ^= 0xFF
upstream = b"\xa5\x48" + hello[2:]
oversize = b"\xa5\x45\x01\x01" + (MAX + 1).to_bytes(2, "little")
streams = [
    ("two_frames", hello + ping),
    ("boot_noise_then_frame", b"ESP-ROM:esp32s3-20210327\r\nboot:0x8 (SPI_FAST_FLASH_BOOT)\r\n" + hello),
    ("corrupt_then_good", bytes(bad) + hello),
    ("upstream_harness_magic_is_ignored", upstream + ping),
    ("oversize_length_resyncs", oversize + ping),
    ("truncated_tail_waits", hello + ping[:5]),
    ("trailing_a5_is_kept", hello + b"\xa5"),
    ("payload_holds_magic", frame(1, J('{"v":"') + MAGIC + J('"}')) + pcm),
    ("frames_back_to_back_with_log", frame(4, J("AD_SOUND beep")) + pcm + hello),
]
lines = [l for l in __doc__.splitlines()[5:] if l.strip()]
out = ["# Shared framing vectors for the Agent Dial USB link (Day 35).",
       "# Generated by tests/gen_frame_vectors.py from SPEC.md's format description. Do not hand-edit.",
       "#"] + ["# " + l.strip() for l in lines] + [
       "#", '# CRC-16/CCITT-FALSE check value for "123456789" = 0x29B1 (asserted at generation).', ""]
for name, t, p in encodes:
    out.append(f"encode\t{name}\t{t}\t{p.hex()}\t{frame(t, p).hex()}")
for name, s in streams:
    frames, d, c = decode(s)
    fr = ",".join(f"{t}:{p.hex()}" for t, p in frames) or "-"
    out.append(f"stream\t{name}\t{s.hex()}\t{fr}\t{d}\t{c}")
Path(__file__).with_name("vectors").joinpath("dial_frame.txt").write_text("\n".join(out) + "\n")
print(f"wrote {len(encodes)} encode and {len(streams)} stream vectors")
